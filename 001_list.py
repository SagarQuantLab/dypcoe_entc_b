# LIST
# [], index, ordered, duplicate allowed, mutable

my_list = [1, 4, 5, 8, 3, 3]

# access first element
print(my_list[0])

# access first two element
print(my_list[0:2])

# access first and 3rd element
print(my_list[0:3:2])

print(my_list)
print(my_list)

# replace first element with 1000
my_list[0] = 1000
print(my_list)

# reverse list
reversed_string = my_list.reverse()
print(reversed_string)
print(my_list)
